// قوة ارتباط كلمة بمفهوم (1 = عضو صريح، ~0.3 = عضو في مفهوم مجاور)
function assoc(word, concept) {
  const list = CONCEPTS[concept];
  if (!list) return 0;
  const i = list.indexOf(word);
  // عضوية صريحة: الكلمات الأولى أكثر تمثيلاً للمفهوم (نموذج البروز)
  if (i >= 0) return 1 - Math.min(0.35, i * 0.012);
  // عضوية في مفهوم مجاور: الذهن يستحضرها أيضاً لكن بقوة أقل.
  // هذا ما يجعل المتوقّع يخطئ أحياناً كما يخطئ الإنسان.
  let best = 0;
  for (const nb of (NEIGHBORS[concept] || [])) {
    const nl = CONCEPTS[nb];
    if (!nl) continue;
    const j = nl.indexOf(word);
    if (j < 0) continue;
    const v = (1 - Math.min(0.35, j * 0.012)) * 0.42;
    if (v > best) best = v;
  }
  return best;
}

// كل المفاهيم التي تصلح تلميحاً لمجموعة كلمات
function conceptsFor(words) {
  const set = new Set();
  for (const w of words) for (const c of (CONCEPT_OF[w] || [])) set.add(c);
  return [...set];
}

module.exports = { CONCEPTS, CONCEPT_OF, NEIGHBORS, assoc, conceptsFor };
